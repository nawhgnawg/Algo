n, m = map(int, input().split())

# dp[i] : 배낭에 담은 보석의 총 무게가 i일 때, 얻을 수 있는 '최대 가치'
# 가치를 구해야 하므로 0으로 초기화합니다.
dp = [0] * (m + 1)

# 1. 보석(무게 w, 가치 v)을 하나씩 살펴봅니다.
for _ in range(n):
    w, v = map(int, input().split())

    # 2. 보석은 한 번만 쓸 수 있으므로, 최대 한도 m부터 뒤에서부터 훑습니다.
    # 당연히 현재 보석의 무게(w)보다 작은 한도에서는 이 보석을 담을 수 없으므로 w까지만 훑습니다.
    for i in range(m, w - 1, -1):
        # 3. 기존에 무게 i를 만들었을 때의 최대 가치와,
        # 과거(i - w)의 상태에서 현재 보석을 추가로 담았을 때의 가치(+v) 중 더 큰 것을 선택!
        dp[i] = max(dp[i], dp[i - w] + v)

print(max(dp))

